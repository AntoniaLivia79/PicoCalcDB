#!/usr/bin/env python3
"""Rebuild the merged files in dist/ from the modules in src/:
   python3 tools/build.py

   dbapp.bas / dbapp_min.bas  - the explorer application
   dblib.bas / dblib_min.bas  - the library for your own programs
   almanac_app.bas            - the almanac application, ready to RUN
*_min files have comments, blank lines and indentation removed
(only ' comments outside "strings" are removed)."""
import os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'src')       # module sources (edit these)
DIST = os.path.join(ROOT, 'dist')     # generated files

def strip_line(l):
    out, inq = [], False
    for ch in l:
        if ch == '"': inq = not inq
        if ch == "'" and not inq: break
        out.append(ch)
    return ''.join(out).strip()

def strip(src):
    return ''.join(s + '\n' for s in map(strip_line, src.split('\n')) if s)

def read(m):
    for d in (SRC, DIST):
        if os.path.exists(os.path.join(d, m)):
            return open(os.path.join(d, m)).read()
    raise FileNotFoundError(m)

# --- library-only: rename SUB/FUNCTION locals and parameters to z_name ---
# MMBasic refuses a program in which a SUB/FUNCTION has the same name as
# a local variable anywhere (e.g. your SUB Rec vs the library's LOCAL rec$),
# and only when that library routine runs. The z_ prefix avoids this.
import re
TOKEN = re.compile(r'"[^"]*"?'                          # string literal
                   r"|'.*"                               # comment
                   r'|&[HhOoBb][0-9A-Fa-f]+'             # &H.. literal
                   r'|(?:\d+\.?\d*|\.\d+)(?:[eE][+-]?\d+)?'  # number
                   r'|[A-Za-z_][A-Za-z0-9_.]*[$%!]?'     # identifier
                   r'|.', re.S)
IDENT = re.compile(r'[A-Za-z_][A-Za-z0-9_.]*')

def base(tok):
    return tok.rstrip('$%!').upper()

def block_names(lines):
    names = set()
    head = lines[0].strip()
    m = re.match(r'(?i)(SUB|FUNCTION)\s+([A-Za-z_][A-Za-z0-9_.]*[$%!]?)(.*)', head)
    params = m.group(3).strip().lstrip('(').rstrip(')')
    for l in [params] + [l.strip()[6:] for l in lines if l.strip().upper().startswith('LOCAL ')]:
        depth, cur, parts = 0, '', []
        for tok in TOKEN.findall(l):
            if tok.startswith("'"): break
            if tok in '([': depth += 1
            if tok in ')]': depth -= 1
            if tok == ',' and depth == 0: parts.append(cur); cur = ''
            else: cur += tok
        parts.append(cur)
        for p in parts:
            mm = IDENT.match(p.strip())
            if mm: names.add(mm.group(0).upper())
    return names

def rename_block(lines, names):
    out = []
    for n, l in enumerate(lines):
        toks, skip_name = TOKEN.findall(l), n == 0
        res = []
        for tok in toks:
            if IDENT.match(tok) and not tok.startswith(("'", '"')):
                if skip_name and base(tok) not in ('SUB', 'FUNCTION'):
                    skip_name = False; res.append(tok); continue
                if base(tok) in names and not skip_name:
                    tok = 'z_' + tok
            res.append(tok)
        out.append(''.join(res))
    return out

def zlocals(src):
    lines, out, i = src.split('\n'), [], 0
    while i < len(lines):
        if re.match(r'(?i)\s*(SUB|FUNCTION)\s', lines[i]):
            j = i
            while not re.match(r'(?i)\s*END\s+(SUB|FUNCTION)\b', lines[j]): j += 1
            blk = lines[i:j + 1]
            out += rename_block(blk, block_names(blk)); i = j + 1
        else:
            out.append(lines[i]); i += 1
    return '\n'.join(out)

def write(name, text):
    for n, l in enumerate(text.split('\n'), 1):
        assert len(l) <= 255, f'{name}:{n} longer than 255 characters'
    open(os.path.join(DIST, name), 'w').write(text)

ENGINE = ['dbcore.bas', 'dbstore.bas', 'dbquery.bas', 'dbexec.bas']
APP = ENGINE + ['dbhal.bas', 'dbgui.bas', 'dbmain.bas']
LIB = ENGINE + ['dbapi.bas']

opts = "OPTION EXPLICIT\nOPTION DEFAULT NONE\n"
write('dbapp.bas', "' dbapp.bas - PicoCalc document database: all modules merged.\n"
      "' Generated by build.py from " + ', '.join(APP) + "\n" + opts +
      ''.join(read(m) + '\n' for m in APP))
write('dbapp_min.bas', opts + ''.join(strip(read(m)) for m in APP))
lib_hdr = ("' =====================================================================\n"
 "' dblib.bas - PicoCalc DB library (engine + public Db* API), merged from\n"
 "' dbcore, dbstore, dbquery, dbexec and dbapi by build.py. See LIBRARY.md.\n"
 "' Use:  #INCLUDE \"dblib.bas\"  near the top of your program, or load\n"
 "' dblib_min.bas and type LIBRARY SAVE to keep it in flash for all programs.\n"
 "' Contains no OPTION statements and no main code: put OPTION EXPLICIT /\n"
 "' OPTION DEFAULT NONE in your own program, before the #INCLUDE.\n"
 "' =====================================================================\n")
write('dblib.bas', lib_hdr + zlocals(''.join(read(m) + '\n' for m in LIB)))
write('dblib_min.bas', "' dblib_min.bas - PicoCalc DB library, comments removed. See LIBRARY.md.\n" +
      zlocals(''.join(strip(read(m)) for m in LIB)))
# Almanac application: library (renamed locals) + display layer + app
write('almanac_app.bas', "' almanac_app.bas - Almanac for the PicoCalc. Generated by build.py from\n"
      "' dblib (dbcore, dbstore, dbquery, dbexec, dbapi), dbhal and almanac.bas.\n" + opts +
      zlocals(''.join(strip(read(m)) for m in LIB)) + strip(read('dbhal.bas')) + strip(read('almanac.bas')))
for f in ['dbapp.bas', 'dbapp_min.bas', 'dblib.bas', 'dblib_min.bas', 'almanac_app.bas']:
    t = read(f); print(f'{f:15} {t.count(chr(10)):5} lines {len(t):6} bytes')
